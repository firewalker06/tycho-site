const {chromium}=require('/Users/didik/Code/personal/tycho-site/node_modules/playwright');
const fs=require('fs');
(async()=>{
 const b=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 const base=process.env.FIRST_RUN_URL;const out=process.env.FIRST_RUN_OUTPUT;
 const p=await b.newPage({viewport:{width:1440,height:1000}});
 await p.goto(base,{waitUntil:'networkidle'});
 await p.getByRole('button',{name:'Create Welcome Sandbox',exact:true}).waitFor();
 await p.screenshot({path:out+'/onboarding-desktop.png'});
 await p.getByRole('button',{name:'Create Welcome Sandbox',exact:true}).click();
 await p.waitForFunction(()=>!document.querySelector('[data-create-welcome-sandbox]'));
 await p.getByRole('button',{name:'New agent',exact:true}).click();
 await p.locator('#agent-prompt').fill('Read README.md and notes.md. Add one practical next step to notes.md, then summarize the change.');
 await p.locator('.agent-options > summary').click();
 await p.locator('.agent-advanced-config > summary').click();
 await p.locator('#agent-harness').selectOption('codex');
 await p.screenshot({path:out+'/create-desktop.png',fullPage:true});
 await p.getByRole('button',{name:'Create and Run',exact:true}).click();
 await p.waitForFunction(()=>location.hash.startsWith('#agent/'));
 await p.waitForFunction(async()=>{const r=await fetch('/agents');const d=await r.json();return d.agents?.some(a=>a.summary==='Added one practical next step to notes.md.');});
 await p.reload({waitUntil:'networkidle'});
 await p.screenshot({path:out+'/result-debug.png',fullPage:true});
 console.log((await p.locator('body').innerText()).slice(-6500));
 await p.getByText('Added one practical next step to notes.md.',{exact:true}).filter({visible:true}).first().waitFor({timeout:10000});
 await p.screenshot({path:out+'/result-desktop.png',fullPage:true});
 const mobile=await b.newPage({viewport:{width:390,height:844}});
 await mobile.goto(base+'/'+new URL(p.url()).hash,{waitUntil:'networkidle'});
 await mobile.getByText('Added one practical next step to notes.md.',{exact:true}).filter({visible:true}).first().waitFor();
 await mobile.screenshot({path:out+'/result-mobile.png',fullPage:true});
 console.log('Chrome '+b.version()+'; browser bootstrap, Options/Advanced harness choice, first agent, saved result, desktop/mobile passed');
 await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
